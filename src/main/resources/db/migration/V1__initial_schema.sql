CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE,
 display_name VARCHAR(80) NOT NULL,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(10) NOT NULL CHECK (role IN ('MEMBER','ADMIN'))
);
CREATE TABLE issues (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(120) NOT NULL,
 description VARCHAR(5000) NOT NULL,
 category VARCHAR(20) NOT NULL CHECK (category IN ('ACCESS','NETWORK','APPLICATION','DEVICE')),
 priority VARCHAR(10) NOT NULL CHECK (priority IN ('LOW','MEDIUM','HIGH','URGENT')),
 status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','IN_PROGRESS','RESOLVED')),
 owner_id BIGINT NOT NULL REFERENCES app_users(id),
 assignee_id BIGINT REFERENCES app_users(id),
 version INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX issues_owner_updated_idx ON issues(owner_id, updated_at DESC, id DESC);
CREATE INDEX issues_status_priority_idx ON issues(status, priority);
CREATE TABLE comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issue_id BIGINT NOT NULL REFERENCES issues(id),
 author_id BIGINT NOT NULL REFERENCES app_users(id),
 body VARCHAR(2000) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX comments_issue_idx ON comments(issue_id, id);
CREATE TABLE audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issue_id BIGINT NOT NULL REFERENCES issues(id),
 actor_id BIGINT NOT NULL REFERENCES app_users(id),
 action VARCHAR(30) NOT NULL,
 detail VARCHAR(1000) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX audit_issue_idx ON audit_events(issue_id, id);
